// Generates src/idl.ts, the part of the two pinned engine IDLs the package uses, from idl/qf_curve.json (qf-curve,
// Project QF original) and idl/qf_pool.json (qf-pool, the raydium-cp-swap fork; Apache-2.0, see
// third_party/raydium-cp-swap/NOTICE). test/idl.test.ts fails if src/idl.ts drifts from this output.
// Run: node packages/engine/scripts/extract-idl.ts
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

type IdlType = string | { defined?: { name: string }; array?: [IdlType, number]; option?: IdlType; vec?: IdlType };
interface RawIdl {
  address: string; metadata: { name: string; version: string };
  instructions: { name: string; discriminator: number[]; accounts: any[]; args: { name: string; type: IdlType }[] }[];
  accounts: { name: string; discriminator: number[] }[];
  events: { name: string; discriminator: number[] }[];
  types: { name: string; type: any; serialization?: string; repr?: { kind: string; packed?: boolean } }[];
}

const here = new URL('../', import.meta.url);
const strip = (f: { name: string; type: IdlType }) => ({ name: f.name, type: f.type });

function subset(file: string, license: string, ixNames: string[] | 'all', accountNames: string[], eventNames: string[] | 'all') {
  const bytes = readFileSync(new URL(`idl/${file}`, here));
  const idl = JSON.parse(bytes.toString('utf8')) as RawIdl;
  const types = new Map<string, unknown>();
  const visit = (t: IdlType): void => {
    if (typeof t === 'string') return;
    if (t.array) return visit(t.array[0]);
    if (t.option !== undefined) return visit(t.option);
    if (t.vec !== undefined) return visit(t.vec);
    if (!t.defined || types.has(t.defined.name)) return;
    const def = idl.types.find((x) => x.name === t.defined!.name);
    if (!def) throw new Error(`${file}: missing type ${t.defined.name}`);
    // zero-copy accounts decode field by field only when packed (no alignment padding)
    if (def.serialization && def.serialization !== 'borsh' && !def.repr?.packed) throw new Error(`${file}: ${def.name} is zero-copy but not packed`);
    const d = def.type.kind === 'enum'
      ? { kind: 'enum', variants: def.type.variants.map((v: any) => (v.fields ? { name: v.name, fields: v.fields } : { name: v.name })) }
      : { kind: 'struct', fields: def.type.fields.map(strip) };
    types.set(def.name, d);
    for (const f of def.type.fields ?? []) visit(f.type);
  };
  const ixs = (ixNames === 'all' ? idl.instructions.map((i) => i.name) : ixNames).map((n) => {
    const ix = idl.instructions.find((i) => i.name === n);
    if (!ix) throw new Error(`${file}: missing instruction ${n}`);
    for (const a of ix.accounts) if (a.optional || a.accounts) throw new Error(`${file}: ${n}.${a.name} is optional or nested (not supported)`);
    ix.args.forEach((a) => visit(a.type));
    return { name: n, discriminator: ix.discriminator, accounts: ix.accounts.map((a: any) => ({ name: a.name, writable: !!a.writable, signer: !!a.signer, address: a.address ?? null })), args: ix.args.map(strip) };
  });
  const accounts = Object.fromEntries(accountNames.map((n) => {
    const a = idl.accounts.find((x) => x.name === n);
    if (!a) throw new Error(`${file}: missing account ${n}`);
    visit({ defined: { name: n } });
    return [n, a.discriminator];
  }));
  const events = Object.fromEntries((eventNames === 'all' ? idl.events.map((e) => e.name) : eventNames).map((n) => {
    const e = idl.events.find((x) => x.name === n), t = idl.types.find((x) => x.name === n);
    if (!e || !t) throw new Error(`${file}: missing event ${n}`);
    t.type.fields.forEach((f: { type: IdlType }) => visit(f.type));
    return [n, { discriminator: e.discriminator, fields: t.type.fields.map(strip) }];
  }));
  for (const e of Object.keys(events)) types.delete(e); // an event's own struct lives under `events`
  return {
    provenance: { file: `idl/${file}`, sha256: createHash('sha256').update(bytes).digest('hex'), idlName: idl.metadata.name, idlVersion: idl.metadata.version, programId: idl.address, license },
    instructions: ixs, accounts, events, types: Object.fromEntries([...types.entries()].sort(([a], [b]) => a.localeCompare(b))),
  };
}

export function generate(): string {
  const curve = subset('qf_curve.json', 'Project QF original (proprietary)', 'all', ['Global', 'Launch'], 'all');
  const pool = subset('qf_pool.json', 'Apache-2.0 (generated from the raydium-cp-swap fork; see third_party/raydium-cp-swap)',
    ['swap_base_input', 'collect_creator_fee_permissionless'], ['AmmConfig', 'PoolState', 'CreatorFeeShare'], 'all');
  return [
    '// GENERATED by packages/engine/scripts/extract-idl.ts from the pinned IDL files in packages/engine/idl/.',
    '// Do not edit by hand; test/idl.test.ts fails on drift.',
    "import type { EngineIdl } from './codec.ts';",
    '',
    `export const CURVE_IDL: EngineIdl = ${JSON.stringify(curve, null, 1)};`,
    '',
    `export const POOL_IDL: EngineIdl = ${JSON.stringify(pool, null, 1)};`,
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('src/idl.ts', here), generate());
  console.log('wrote packages/engine/src/idl.ts');
}
